// Builds the website into dist/: the home page with the facts of the release feeds, a page for every Markdown file in pages/,
// the same pages as Markdown, llms.txt, and sitemap.xml. Then checks that every link inside the site
// leads to a file and, with a #, to an element of that file.
// Usage: node build.mjs
import { execFileSync } from "node:child_process";
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { page, read, reference } from "./docs.mjs";
import { status } from "./status.mjs";
import { gameData } from "./gamedata.mjs";
import { gallery } from "./gallery.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "dist");
const site = "https://angelicaproject.github.io/angelica/";
const raw = "https://raw.githubusercontent.com/AngelicaProject/angelica/main/";

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
// The home page states what the release feeds give at build time; pages.yml rebuilds hourly.
const { files: mapFiles, ...facts } = await status();
execFileSync(process.execPath, [join(here, "home.mjs"), join(here, "art"), join(dist, "index.html"), JSON.stringify(facts)], { stdio: "inherit" });

const sources = readdirSync(join(here, "pages")).filter((f) => f.endsWith(".md")).sort();
const docs = sources.map((f) => ({ file: f.replace(/\.md$/, ".html"), ...read(readFileSync(join(here, "pages", f), "utf8")) }))
  .sort((a, b) => (Number(a.front.order) || 99) - (Number(b.front.order) || 99));
const pages = Object.fromEntries([...docs.map((d) => [d.title.replace(/^[^:]+: /, ""), d.file]), ...reference.map((r) => [r.title, r.file]), ["Game data", "reference-game-data.html"], ["Interface parts", "reference-interface-parts.html"]]);
// Instructions for a coding agent, served as they are.
copyFileSync(join(here, "agent-setup.md"), join(dist, "agent-setup.md"));
for (const d of docs) {
  writeFileSync(join(dist, d.file), page(d, d.file, pages));
  writeFileSync(join(dist, d.file.replace(/\.html$/, ".md")), d.md.trimStart());
}
// What the released game map describes, for Lens queries, generated from its files.
const gameMd = gameData(mapFiles, facts.map.version);
writeFileSync(join(dist, "reference-game-data.html"), page({ front: { section: "Reference", kicker: "Reference" }, md: gameMd, title: "Game data" }, "reference-game-data.html", pages, {
  generated: { text: `Generated from game map ${facts.map.version} when the site is built.`, href: `https://github.com/AngelicaProject/angelica-gamemap/tree/v${facts.map.version}` },
}));
writeFileSync(join(dist, "reference-game-data.md"), gameMd);
// Every place and part, drawn by the host's renderer into gallery/ (gallery.mjs), with its pictures.
const partsMd = gallery(join(here, "gallery")) ?? `# Interface parts

The pictures of this page are drawn on Windows by the host's gallery test; this build was made without them. See docs/development/website.md.
`;
writeFileSync(join(dist, "reference-interface-parts.html"), page({ front: { section: "Reference", kicker: "Reference" }, md: partsMd, title: "Interface parts" }, "reference-interface-parts.html", pages, {
  generated: { text: "Drawn when the site is built, from the examples in angelica-view.", href: "https://github.com/AngelicaProject/angelica/blob/main/crates/angelica-view/src/examples.rs" },
}));
writeFileSync(join(dist, "reference-interface-parts.md"), partsMd);
if (existsSync(join(here, "gallery"))) cpSync(join(here, "gallery"), join(dist, "gallery"), { recursive: true });
// The Rust SDK's reference, generated by rustdoc from its source, under sdk/.
const repoRoot = join(here, "..");
execFileSync("cargo", ["rustdoc", "--quiet", "--locked", "-p", "angelica-sdk", "--target", "wasm32-wasip2", "--", "--html-before-content", join(here, "sdk-header.html")], { cwd: repoRoot, stdio: "inherit" });
cpSync(join(repoRoot, "target", "wasm32-wasip2", "doc"), join(dist, "sdk"), { recursive: true });
// The canonical documents an author or a maintainer looks up, as Reference pages, and as they are in Markdown.
for (const r of reference) {
  const text = readFileSync(join(here, "..", "docs", r.path), "utf8");
  const shown = { front: { section: "Reference", kicker: "Reference" }, md: text, title: r.title };
  writeFileSync(join(dist, r.file), page(shown, r.file, pages, { source: `docs/${r.path}`, lede: r.lede }));
  writeFileSync(join(dist, r.file.replace(/\.html$/, ".md")), text);
}

// llms.txt: what an agent reads first. Every page as Markdown, then the canonical documents an author needs.
const lede = (md) => md.replace(/^# .+$/m, "").trim().split(/\r?\n\r?\n/)[0].replace(/\s+/g, " ").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");
const listed = (section) => docs.filter((d) => (d.front.section || "Build") === section).map((d) => `- [${d.title.replace(/^[^:]+: /, "")}](${site}${d.file.replace(/\.html$/, ".md")}): ${lede(d.md)}`);
const canonical = [
  ["Writing a plugin", "docs/plugins/authoring.md", "The steps from an empty folder to a published plugin, with the commands."],
  ["Interface cards", "docs/plugins/interfaces.md", "What each part of the plugin API does, its permission, and how to use it."],
  ["Plugin API 1.0", "docs/formats/plugin-api-v1.md", "The contract between a plugin and the host."],
  ["Plugin manifest", "docs/formats/plugin-manifest-v1.md", "The fields of angelica.toml."],
  ["Permissions", "docs/architecture/permissions.md", "Every permission, what it allows, and how the player sees it."],
  ["API requests", "docs/plugins/api-requests.md", "How to ask for an operation the API does not have."],
];
writeFileSync(join(dist, "llms.txt"), `# Angelica

> A plugin platform for FINAL FANTASY XIV (FFXIV). A plugin is a Rust WebAssembly component that runs in a sandbox and can do only what the player allowed. It names entries of the game map instead of game addresses, so it keeps working across game patches.

To set up an FFXIV plugin project, follow [Set up an Angelica plugin project](${site}agent-setup.md); the project's AGENTS.md then guides the work.

The same instructions come as an agent skill, \`ffxiv-plugin\`. In Claude Code: \`claude plugin marketplace add AngelicaProject/angelica\`, then \`claude plugin install angelica@angelica\`. In other agents that read Agent Skills: \`gh skill install AngelicaProject/angelica ffxiv-plugin\`.

## Players

${listed("Play").join("\n")}

## Plugin authors

${listed("Build").join("\n")}
${canonical.map(([t, path, about]) => `- [${t}](${raw}${path}): ${about}`).join("\n")}

## How Angelica works

${listed("Understand").join("\n")}

## Optional

- [Architecture overview](${raw}docs/architecture/overview.md): The components of Angelica and what each owns.
- [Product principles](${raw}docs/product/principles.md): The invariants every change keeps.
`);

// sitemap.xml: every page for search engines.
const listedPages = ["", ...readdirSync(dist).filter((f) => f.endsWith(".html") && f !== "index.html").sort()];
writeFileSync(join(dist, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${listedPages.map((f) => `<url><loc>${site}${f}</loc></url>`).join("\n")}
</urlset>
`);

// Every link that stays inside the site must lead somewhere.
const broken = [];
for (const file of readdirSync(dist).filter((f) => f.endsWith(".html"))) {
  const html = readFileSync(join(dist, file), "utf8");
  for (const [, href] of html.matchAll(/\s(?:href|src)="([^"]*)"/g)) {
    if (/^(?:[a-z]+:|\/\/|data:)/i.test(href)) continue;
    const [target, hash] = href.split("#");
    const into = target || file;
    let text;
    try { text = readFileSync(join(dist, into), "utf8"); } catch { broken.push(`${file}: ${href}`); continue; }
    if (hash && into.endsWith(".html") && !new RegExp(`\\sid="${hash.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}"`).test(text)) broken.push(`${file}: ${href}`);
  }
}
if (broken.length) {
  console.error(`Links that lead nowhere:\n${broken.join("\n")}`);
  process.exit(1);
}
console.log(`built ${docs.length + reference.length + 2} pages and the Rust SDK reference into dist/`);
