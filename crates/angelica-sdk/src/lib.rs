/// Lets `?` turn a host error into the message that [`Plugin`]'s methods
/// return.
impl From<Error> for String {
    fn from(error: Error) -> Self {
        error.message
    }
}

/// A plugin. The host creates it with [`Plugin::start`] when the plugin is
/// enabled and drops it after [`Plugin::stop`].
pub trait Plugin: Sized + 'static {
    /// # Errors
    /// An error disables the plugin and is shown to the player.
    fn start() -> Result<Self, String>;

    /// Called every frame; `elapsed` is the time in seconds since the
    /// previous `tick`. Sum it to measure time, or use `std::time::Instant`
    /// and `SystemTime`, which work in a plugin.
    ///
    /// # Errors
    /// An error disables the plugin and is shown to the player.
    fn tick(&mut self, _elapsed: f64) -> Result<(), String> {
        Ok(())
    }

    /// The plugin's windows for this frame.
    fn ui(&mut self) -> Vec<ui::Window> {
        Vec::new()
    }

    /// The plugin's panels for this frame: small parts of the screen the
    /// player places and keeps in view (see [`ui::Panel`]).
    fn panels(&mut self) -> Vec<ui::Panel> {
        Vec::new()
    }

    /// The plugin's entries in the game's menus for this frame, such as
    /// the menu of an item (see [`ui::MenuEntry`]); the player's choice
    /// arrives as `ui::Event::MenuChosen`.
    fn menu_entries(&mut self) -> Vec<ui::MenuEntry> {
        Vec::new()
    }

    /// A player action in a window, a panel, or the Angelica menu.
    fn ui_event(&mut self, _event: ui::Event) {}

    /// A command of the plugin the player ran (see [`commands`]).
    ///
    /// # Errors
    /// The error is printed in the chat log as the plugin's message.
    fn command(&mut self, _invocation: commands::Invocation) -> Result<(), String> {
        Ok(())
    }

    /// A firing of one of the plugin's watches, a message from another
    /// plugin, or what happened on its connections (see [`events`]).
    fn game_event(&mut self, _event: events::GameEvent) {}

    /// Called before the plugin is disabled.
    fn stop(&mut self) {}

    /// Runs a job in a separate instance, where `start` has not run.
    ///
    /// # Errors
    /// The error is what `jobs.poll` reports.
    fn run_job(name: &str, _input: Vec<u8>) -> Result<Vec<u8>, String> {
        Err(format!("this plugin has no job {name}"))
    }

    /// Runs in an intercept instance on the game's call of a function the
    /// plugin intercepts with [`intercepts::before`] or
    /// [`intercepts::after`]. It has no `self`: the instance shares nothing
    /// with the main one but the snapshot.
    fn intercepted(_call: intercepts::Call) {}

    /// Runs in a new intercept instance, in the background, after the main
    /// instance published a snapshot with
    /// [`intercepts::publish_snapshot`]: reads [`intercepts::snapshot`]
    /// into the instance's own memory, where handlers find it. It has up to
    /// 30 s; handlers keep the instance they had until it returns `Ok`.
    ///
    /// # Errors
    /// Why the snapshot cannot be prepared; handlers keep the one they had.
    fn prepare() -> Result<(), String> {
        Ok(())
    }

    /// The player's input of this frame on the plugin's surfaces (see
    /// [`gpu`]), before [`Plugin::tick`].
    fn surface_input(&mut self, _events: Vec<gpu::SurfaceEvent>) {}

    /// Runs in an intercept instance when the game calls a thunk the
    /// plugin made with [`calls::thunk`], under a handler's rules: gives
    /// what the thunk returns, `Value::None` for one that returns nothing.
    /// A value of another type makes the thunk call its fallback.
    #[must_use]
    fn thunk(_call: calls::ThunkCall) -> memory::Value {
        memory::Value::None
    }
}

/// Logs a line at a level.
pub fn log(level: api::runtime::Level, message: &str) {
    api::runtime::log(level, message);
}

/// Logs an informational line.
pub fn info(message: &str) {
    log(api::runtime::Level::Info, message);
}

/// Logs a warning.
pub fn warning(message: &str) {
    log(api::runtime::Level::Warning, message);
}

/// Logs an error.
pub fn error(message: &str) {
    log(api::runtime::Level::Error, message);
}

/// Exports a [`Plugin`] as the component's guest.
#[macro_export]
macro_rules! plugin {
    ($plugin:ty) => {
        const _: () = {
            ::std::thread_local! {
                static STATE: ::std::cell::RefCell<::std::option::Option<$plugin>> =
                    const { ::std::cell::RefCell::new(::std::option::Option::None) };
            }

            fn with<R>(default: R, call: impl FnOnce(&mut $plugin) -> R) -> R {
                STATE.with(|state| match state.borrow_mut().as_mut() {
                    ::std::option::Option::Some(plugin) => call(plugin),
                    ::std::option::Option::None => default,
                })
            }

            struct Guest;

            impl $crate::bindings::exports::angelica::plugin::guest::Guest for Guest {
                fn start() -> ::std::result::Result<(), ::std::string::String> {
                    let plugin = <$plugin as $crate::Plugin>::start()?;
                    STATE.with(|state| *state.borrow_mut() = ::std::option::Option::Some(plugin));
                    ::std::result::Result::Ok(())
                }

                fn stop() {
                    with((), $crate::Plugin::stop);
                    STATE.with(|state| *state.borrow_mut() = ::std::option::Option::None);
                }

                fn tick(elapsed: f64) -> ::std::result::Result<(), ::std::string::String> {
                    with(::std::result::Result::Ok(()), |plugin| {
                        $crate::Plugin::tick(plugin, elapsed)
                    })
                }

                fn ui() -> ::std::vec::Vec<$crate::bindings::angelica::plugin::ui::Place> {
                    with(::std::vec::Vec::new(), |plugin| {
                        let windows = $crate::Plugin::ui(plugin);
                        let panels = $crate::Plugin::panels(plugin);
                        let entries = $crate::Plugin::menu_entries(plugin);
                        $crate::ui::view_to_wit(windows, panels, entries)
                    })
                }

                fn ui_event(event: $crate::bindings::angelica::plugin::ui::Event) {
                    if let ::std::option::Option::Some(event) = $crate::ui::event_from_wit(event) {
                        with((), |plugin| $crate::Plugin::ui_event(plugin, event));
                    }
                }

                fn command(
                    invocation: $crate::commands::Invocation,
                ) -> ::std::result::Result<(), ::std::string::String> {
                    with(::std::result::Result::Ok(()), |plugin| {
                        $crate::Plugin::command(plugin, invocation)
                    })
                }

                fn on_game_event(event: $crate::events::GameEvent) {
                    with((), |plugin| $crate::Plugin::game_event(plugin, event));
                }

                fn run_job(
                    name: ::std::string::String,
                    input: ::std::vec::Vec<u8>,
                ) -> ::std::result::Result<::std::vec::Vec<u8>, ::std::string::String> {
                    <$plugin as $crate::Plugin>::run_job(&name, input)
                }
            }

            impl $crate::bindings::exports::angelica::plugin::handler::Guest for Guest {
                fn prepare() -> Result<(), String> {
                    <$plugin as $crate::Plugin>::prepare()
                }

                fn intercepted(call: $crate::intercepts::Call) {
                    <$plugin as $crate::Plugin>::intercepted(call);
                }
            }

            impl $crate::bindings::exports::angelica::plugin::surface_handler::Guest for Guest {
                fn surface_input(events: ::std::vec::Vec<$crate::gpu::SurfaceEvent>) {
                    STATE.with(|state| {
                        if let Some(plugin) = state.borrow_mut().as_mut() {
                            <$plugin as $crate::Plugin>::surface_input(plugin, events);
                        }
                    });
                }
            }

            impl $crate::bindings::exports::angelica::plugin::thunk_handler::Guest for Guest {
                fn called(call: $crate::calls::ThunkCall) -> $crate::memory::Value {
                    <$plugin as $crate::Plugin>::thunk(call)
                }
            }

    $crate::bindings::export!(Guest with_types_in $crate::bindings);
        };
    };
}
