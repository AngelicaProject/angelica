//! Native compiler artifacts are accepted only through the authenticated package path.
use wasmtime::{Engine, component::Component};

/// # Safety
/// `bytes` must be an authenticated release artifact produced by the trusted wasmtime
/// compiler from validated component source. Arbitrary plugin-authored native artifacts
/// must never be signed or passed here. Version and engine compatibility remain checked.
pub(super) unsafe fn load_authenticated(
    engine: &Engine,
    bytes: &[u8],
) -> Result<Component, String> {
    // SAFETY: the caller authenticated these exact bytes from a trusted compiler release;
    // wasmtime additionally checks the serialized version and engine configuration.
    unsafe { Component::deserialize(engine, bytes) }.map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn loads_trusted_compiler_output_and_rejects_corruption() {
        let sandbox = crate::sandbox::Sandbox::new().unwrap();
        let source = b"\0asm\x0d\0\x01\0";
        let component = Component::new(&sandbox.engine, source).unwrap();
        let artifact = component.serialize().unwrap();
        // SAFETY: this artifact was generated by our trusted compiler above, with the same engine.
        assert!(unsafe { load_authenticated(&sandbox.engine, &artifact) }.is_ok());
        // SAFETY: empty bytes contain no native code and must fail artifact validation.
        assert!(unsafe { load_authenticated(&sandbox.engine, &[]) }.is_err());
    }
}
