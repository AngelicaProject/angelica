//! `angelica map labels`: a Ghidra script that names, in a program of the
//! game's executable, every function, location, global, and vtable the map
//! resolves to in that build, so map work reads the game's code in the
//! map's names.
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use angelica_map::{EntryKind, Map, Value};
use angelica_pe::{Image, Layout};
use clap::Args;
use serde_json::json;

use crate::Output;

const EXECUTABLE: &str = "ffxiv_dx11.exe";
/// The script's class; Ghidra asks a Java script's file to have its name.
const CLASS: &str = "AngelicaMapLabels";

#[derive(Debug, Args)]
pub struct LabelsArgs {
    /// The map directory (the one with `map.toml`).
    #[arg(long)]
    map: PathBuf,
    /// The game's `game` folder, with `ffxiv_dx11.exe`.
    #[arg(long)]
    game: PathBuf,
    /// Where to write the script; `AngelicaMapLabels.java` in this folder
    /// unless given.
    #[arg(long)]
    output: Option<PathBuf>,
    #[command(flatten)]
    reporting: Output,
}

/// One name to put into the program.
struct Label {
    rva: u32,
    name: String,
    function: bool,
}

pub fn run(args: &LabelsArgs) -> ExitCode {
    match labels(args) {
        Ok((path, count)) => {
            if args.reporting.json {
                println!(
                    "{}",
                    json!({"written": path.display().to_string(), "labels": count})
                );
            } else {
                println!(
                    "wrote {} with {count} labels; run it in Ghidra's Script Manager on the program of this executable",
                    path.display()
                );
            }
            ExitCode::SUCCESS
        }
        Err(error) => {
            if args.reporting.json {
                println!("{}", json!({"error": {"code": "labels", "message": error}}));
            } else {
                eprintln!("error: {error}");
            }
            ExitCode::FAILURE
        }
    }
}

fn labels(args: &LabelsArgs) -> Result<(PathBuf, usize), String> {
    let map = Map::load(&args.map).map_err(|error| error.to_string())?;
    let path = args.game.join(EXECUTABLE);
    let executable = std::fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let image = Image::parse(&executable, Layout::File)
        .map_err(|error| format!("{}: {error}", path.display()))?;
    let resolution = map.resolve(&image, image.image_base());
    let labels: Vec<Label> = resolution
        .present()
        .filter_map(|(name, value)| {
            let Value::Address(rva) = value else {
                return None;
            };
            let function = match map.get(name).map(|entry| &entry.kind) {
                Some(EntryKind::Function { .. }) => true,
                Some(
                    EntryKind::Location { .. }
                    | EntryKind::Global { .. }
                    | EntryKind::Vtable { .. },
                ) => false,
                _ => return None,
            };
            Some(Label {
                rva,
                name: name.to_owned(),
                function,
            })
        })
        .collect();
    let output = args
        .output
        .clone()
        .unwrap_or_else(|| PathBuf::from(format!("{CLASS}.java")));
    let script = script(&labels, &crate::verify::sha256_hex(&executable), &output)?;
    std::fs::write(&output, script).map_err(|e| format!("{}: {e}", output.display()))?;
    Ok((output, labels.len()))
}

/// The Java source of the script.
fn script(labels: &[Label], sha256: &str, output: &Path) -> Result<String, String> {
    if output.file_stem().and_then(|stem| stem.to_str()) != Some(CLASS) {
        return Err(format!(
            "Ghidra runs a Java script only from a file named after its class: {CLASS}.java"
        ));
    }
    let calls = labels.iter().fold(String::new(), |mut calls, label| {
        let _ = writeln!(
            calls,
            "        label(0x{:X}L, \"{}\", {});",
            label.rva, label.name, label.function
        );
        calls
    });
    Ok(TEMPLATE
        .replace("@CLASS@", CLASS)
        .replace("@SHA256@", sha256)
        .replace("@LABELS@\n", &calls)
        .replace("@COUNT@", &labels.len().to_string()))
}

/// The script, with `@CLASS@`, `@SHA256@`, `@LABELS@`, and `@COUNT@` to
/// fill in. Entry names are lowercase words, digits, underscores, and dots,
/// so they need no escaping in a Java string.
const TEMPLATE: &str = r#"// Names the game map's entries in this program of the game's executable.
// Generated by `angelica map labels`; run it again after the map or the game changes.
//@category Angelica
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.symbol.SourceType;

public class @CLASS@ extends GhidraScript {
    private static final String EXECUTABLE_SHA256 = "@SHA256@";

    @Override
    public void run() throws Exception {
        if (!EXECUTABLE_SHA256.equalsIgnoreCase(currentProgram.getExecutableSHA256())) {
            printerr("This program is not the executable the labels were made for.");
            return;
        }
@LABELS@
        println("@COUNT@ labels from the game map");
    }

    /** Names one entry; a name that cannot be set is reported and skipped. */
    private void label(long rva, String name, boolean function) {
        Address at = currentProgram.getImageBase().add(rva);
        try {
            if (function) {
                Function found = getFunctionAt(at);
                if (found == null) {
                    found = createFunction(at, null);
                }
                if (found != null) {
                    found.setName(name, SourceType.USER_DEFINED);
                    return;
                }
            }
            createLabel(at, name, true, SourceType.USER_DEFINED);
        } catch (Exception e) {
            printerr(name + " at " + at + ": " + e.getMessage());
        }
    }
}
"#;
