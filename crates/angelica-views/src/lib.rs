//! Views of Anatomia for Rust plugins: a typed wrapper of a handle for every
//! structure, with a method per field, a function per global, and the
//! values of every enum. The views name entries, never offsets: the host
//! resolves the names in the running game, so views stay valid across game
//! builds while the description's names do.
//!
//! A plugin generates views of its own entries in its `build.rs`:
//!
//! ```ignore
//! fn main() {
//!     angelica_views::build().unwrap();
//! }
//! ```
//!
//! and includes them:
//!
//! ```ignore
//! mod own {
//!     include!(concat!(env!("OUT_DIR"), "/anatomia.rs"));
//! }
//! ```
//!
//! The SDK's `game` module holds the views of the central description,
//! generated with `angelica anatomia views`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::PathBuf;

use angelica_anatomia::{Anatomia, Enum, Kind, Place, Primitive, Struct, StructField, Ty, TypeDef};

/// How deep a structure's bases go.
const MOST_BASES: usize = 8;

/// Views of `anatomia`, as Rust source: one module per area. `sdk` is the
/// path of the SDK crate where the source is compiled, `::angelica_sdk` in
/// a plugin. `central` leaves out globals that hold no object, which the
/// host reads only for a plugin's own entries.
#[must_use]
pub fn generate(anatomia: &Anatomia, sdk: &str, central: bool) -> String {
    let views = Views { anatomia };
    let mut areas: BTreeMap<&str, Area<'_>> = BTreeMap::new();
    for (name, definition) in anatomia.types() {
        if anatomia.broken().contains_key(name) {
            continue;
        }
        match definition {
            TypeDef::Struct(structure) => {
                areas.entry(area(name)).or_default().structs.push(structure);
            }
            TypeDef::Enum(enumeration) => {
                areas.entry(area(name)).or_default().enums.push(enumeration);
            }
            _ => {}
        }
    }
    for entry in anatomia.entries() {
        if let (Kind::Function { ty, .. }, false) = (&entry.kind, central) {
            areas.entry(area(&entry.name)).or_default().functions.push((
                &entry.name,
                ty,
                entry.doc.as_deref(),
            ));
        }
        if let Kind::Global { ty } = &entry.kind {
            let holds = views.object_type(ty);
            if holds || !central {
                areas.entry(area(&entry.name)).or_default().globals.push((
                    &entry.name,
                    ty,
                    entry.doc.as_deref(),
                ));
            }
        }
    }
    let mut out = String::from("// Generated by angelica-views from Anatomia. Do not edit.\n");
    for (name, area) in &areas {
        let _ = writeln!(out, "\n/// The views of the area `{name}`.");
        out.push_str(
            "#[allow(clippy::all, clippy::pedantic, missing_docs, non_snake_case, dead_code, unused_imports)]\n",
        );
        let _ = writeln!(out, "pub mod {} {{", ident(name));
        let _ = writeln!(
            out,
            "    use {sdk}::memory::{{self, Array, Field, FromValue, Handle, Pointer, Value, View}};
    use {sdk}::calls;"
        );
        let _ = writeln!(out, "    use {sdk}::Error;");
        for enumeration in &area.enums {
            Views::enumeration(&mut out, enumeration);
        }
        for structure in &area.structs {
            views.structure(&mut out, structure);
        }
        for (global, ty, doc) in &area.globals {
            views.global(&mut out, global, ty, *doc);
        }
        for (function, ty, doc) in &area.functions {
            views.function(&mut out, sdk, function, ty, *doc);
        }
        out.push_str("}\n");
    }
    out
}

/// For a plugin's `build.rs`: writes the views of the `anatomia/` folder
/// beside its `Cargo.toml` to `anatomia.rs` in `OUT_DIR`, and has Cargo
/// run it again when the folder changes.
///
/// # Errors
/// A folder that is not a description, and a file that cannot be written.
pub fn build() -> Result<(), String> {
    let manifest = std::env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR is not set")?;
    let out = std::env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?;
    let directory = PathBuf::from(manifest).join("anatomia");
    println!("cargo:rerun-if-changed={}", directory.display());
    let anatomia = Anatomia::load(&directory).map_err(|error| error.to_string())?;
    let path = PathBuf::from(out).join("anatomia.rs");
    std::fs::write(&path, generate(&anatomia, "::angelica_sdk", false))
        .map_err(|error| format!("{}: {error}", path.display()))
}

#[derive(Default)]
struct Area<'a> {
    structs: Vec<&'a Struct>,
    enums: Vec<&'a Enum>,
    globals: Vec<(&'a str, &'a Ty, Option<&'a str>)>,
    functions: Vec<(&'a str, &'a angelica_anatomia::FnType, Option<&'a str>)>,
}

fn area(name: &str) -> &str {
    name.split('.').next().unwrap_or(name)
}

/// The name without its area.
fn subject(name: &str) -> &str {
    name.split_once('.').map_or(name, |(_, rest)| rest)
}

fn camel(name: &str) -> String {
    subject(name)
        .split(['.', '_'])
        .filter(|word| !word.is_empty())
        .map(|word| {
            let mut letters = word.chars();
            letters
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + letters.as_str())
                .unwrap_or_default()
        })
        .collect()
}

const KEYWORDS: [&str; 39] = [
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
    "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while",
    "abstract", "box", "final", "macro", "try",
];

/// `name` as a Rust identifier.
fn ident(name: &str) -> String {
    match name {
        "self" | "super" | "crate" | "Self" => format!("{name}_"),
        _ if KEYWORDS.contains(&name) => format!("r#{name}"),
        _ => name.to_owned(),
    }
}

fn doc(out: &mut String, indent: &str, text: Option<&str>) {
    for line in text.unwrap_or_default().lines() {
        let _ = writeln!(out, "{indent}/// {line}");
    }
}

/// A Rust string literal of `text`.
fn literal(text: &str) -> String {
    format!("{text:?}")
}

struct Views<'a> {
    anatomia: &'a Anatomia,
}

impl Views<'_> {
    fn plain<'t>(&'t self, ty: &'t Ty) -> &'t Ty {
        let mut ty = ty;
        for _ in 0..8 {
            match ty {
                Ty::Named(name, args) if args.is_empty() => match self.anatomia.types().get(name) {
                    Some(TypeDef::Alias { ty: inner, .. }) => ty = inner,
                    _ => return ty,
                },
                _ => return ty,
            }
        }
        ty
    }

    fn structure_of(&self, name: &str) -> Option<&Struct> {
        match self.anatomia.types().get(name) {
            Some(TypeDef::Struct(structure)) if !self.anatomia.broken().contains_key(name) => {
                Some(structure)
            }
            _ => None,
        }
    }

    /// Whether a value of `ty` is an object or a pointer to one.
    fn object_type(&self, ty: &Ty) -> bool {
        let ty = match self.plain(ty) {
            Ty::Ptr(Some(inner)) => self.plain(inner),
            plain => plain,
        };
        matches!(ty, Ty::Named(name, args) if args.is_empty() && self.structure_of(name).is_some())
    }

    /// The path of the view of the structure `name`.
    fn path(name: &str) -> String {
        format!("super::{}::{}", ident(area(name)), camel(name))
    }

    /// The Rust type a number of `ty` reads as.
    fn number(&self, ty: &Ty) -> Option<&'static str> {
        match self.plain(ty) {
            Ty::Primitive(primitive) => Some(primitive.name()),
            Ty::Char8 => Some("u8"),
            Ty::Named(name, args) if args.is_empty() => match self.anatomia.types().get(name) {
                Some(TypeDef::Enum(enumeration)) => enumeration.ty.map(Primitive::name),
                _ => None,
            },
            _ => None,
        }
    }

    /// The Rust type an element of an array of `ty` reads as.
    fn element(&self, ty: &Ty) -> Option<String> {
        if let Some(number) = self.number(ty) {
            return Some(number.to_owned());
        }
        match self.plain(ty) {
            Ty::Named(name, args) if args.is_empty() && self.structure_of(name).is_some() => {
                Some(Self::path(name))
            }
            Ty::Ptr(Some(inner)) => match self.plain(inner) {
                Ty::Named(name, args) if args.is_empty() && self.structure_of(name).is_some() => {
                    Some(format!("Option<{}>", Self::path(name)))
                }
                _ => None,
            },
            _ => None,
        }
    }

    /// The Rust type a value of `ty` reads as; none for one no view reads.
    fn read_type(&self, ty: &Ty) -> Option<String> {
        if let Some(number) = self.number(ty) {
            return Some(number.to_owned());
        }
        match self.plain(ty) {
            Ty::Named(name, args) if args.is_empty() && self.structure_of(name).is_some() => {
                Some(Self::path(name))
            }
            Ty::Array(inner, _) if matches!(self.plain(inner), Ty::Char8) => Some("Vec<u8>".into()),
            Ty::Array(inner, _) => Some(format!("Array<{}>", self.element(inner)?)),
            Ty::Ptr(None) => Some("Option<Pointer>".into()),
            Ty::Ptr(Some(inner)) => match self.plain(inner) {
                Ty::Char8 => Some("Vec<u8>".into()),
                Ty::Named(name, args) if args.is_empty() && self.structure_of(name).is_some() => {
                    Some(format!("Option<{}>", Self::path(name)))
                }
                Ty::Array(element, _) => Some(format!("Option<Array<{}>>", self.element(element)?)),
                _ => Some("Option<Pointer>".into()),
            },
            Ty::Opaque => Some("Pointer".into()),
            _ => None,
        }
    }

    /// The Rust type a write of `ty` takes; none for one no view writes.
    fn write_type(&self, ty: &Ty) -> Option<String> {
        if let Some(number) = self.number(ty) {
            return Some(number.to_owned());
        }
        match self.plain(ty) {
            Ty::Array(inner, _) if matches!(self.plain(inner), Ty::Char8) => Some("&[u8]".into()),
            Ty::Ptr(Some(inner)) => match self.plain(inner) {
                Ty::Named(name, args) if args.is_empty() && self.structure_of(name).is_some() => {
                    Some(format!("Option<&{}>", Self::path(name)))
                }
                Ty::Char8 => None,
                _ => Some("Option<Pointer>".into()),
            },
            Ty::Ptr(None) => Some("Option<Pointer>".into()),
            _ => None,
        }
    }

    fn enumeration(out: &mut String, enumeration: &Enum) {
        let ty = enumeration.ty.map_or("u64", Primitive::name);
        let _ = writeln!(out);
        doc(out, "    ", enumeration.doc.as_deref());
        let module = ident(&subject(&enumeration.name).replace('.', "_"));
        let _ = writeln!(out, "    pub mod {module} {{");
        let bits = enumeration.ty.map_or(64, |primitive| primitive.size() * 8);
        let signed = enumeration
            .ty
            .is_some_and(|primitive| ty.starts_with('i') && primitive.is_integer());
        let largest = if signed {
            (1u64 << (bits - 1)) - 1
        } else {
            u64::MAX >> (64 - bits)
        };
        for (name, value) in &enumeration.values {
            // A value past the type's range is the bits the game stores.
            let value = if *value <= largest {
                value.to_string()
            } else {
                format!("{value}_u64 as {ty}")
            };
            let _ = writeln!(
                out,
                "        pub const {}: {ty} = {value};",
                ident(&name.to_ascii_uppercase())
            );
        }
        out.push_str("    }\n");
    }

    /// Every field of `structure` and of its bases, by name, with the
    /// structure that declares it; a field of the structure itself hides a
    /// base's field of the same name.
    fn fields<'s>(
        &'s self,
        structure: &'s Struct,
    ) -> BTreeMap<&'s str, (&'s str, &'s StructField)> {
        let mut fields = BTreeMap::new();
        let mut queue = vec![(structure, 0)];
        let mut seen = BTreeSet::new();
        while let Some((current, depth)) = queue.pop() {
            if !seen.insert(current.name.as_str()) {
                continue;
            }
            for (name, field) in &current.fields {
                fields
                    .entry(name.as_str())
                    .or_insert((current.name.as_str(), field));
            }
            if depth < MOST_BASES {
                for (base, _) in current.extends.iter().rev() {
                    if let Some(base) = self.structure_of(base) {
                        queue.push((base, depth + 1));
                    }
                }
            }
        }
        fields
    }

    fn structure(&self, out: &mut String, structure: &Struct) {
        let view = camel(&structure.name);
        let _ = writeln!(out);
        doc(out, "    ", structure.doc.as_deref());
        let _ = writeln!(out, "    #[derive(Debug, Clone, Copy, PartialEq, Eq)]");
        let _ = writeln!(out, "    pub struct {view}(Handle);");
        let _ = writeln!(
            out,
            "    impl View for {view} {{\n        const STRUCTURE: &'static str = {};\n        fn from_handle(handle: Handle) -> Self {{\n            Self(handle)\n        }}\n        fn handle(&self) -> Handle {{\n            self.0\n        }}\n    }}",
            literal(&structure.name)
        );
        let _ = writeln!(
            out,
            "    impl FromValue for {view} {{\n        fn from_value(value: Value) -> Result<Self, Error> {{\n            memory::object(value)\n        }}\n    }}"
        );
        let _ = writeln!(out, "    impl {view} {{");
        for (name, (declaring, field)) in self.fields(structure) {
            self.field(out, name, declaring, field);
        }
        out.push_str("    }\n");
    }

    fn field(&self, out: &mut String, name: &str, declaring: &str, field: &StructField) {
        let (read, write) = match &field.place {
            Place::Bits { .. } => {
                let ty = if matches!(self.plain(&field.ty), Ty::Primitive(Primitive::Bool)) {
                    "bool"
                } else {
                    "u64"
                };
                (Some(ty.to_owned()), Some(ty.to_owned()))
            }
            Place::Located => (self.read_type(&field.ty), self.write_type(&field.ty)),
        };
        let Some(read) = read else {
            return;
        };
        let entry = literal(&format!("{declaring}.{name}"));
        let method = ident(name);
        let _ = writeln!(out);
        doc(out, "        ", field.doc.as_deref());
        let _ = writeln!(
            out,
            "        pub fn {method}(&self) -> Result<{read}, Error> {{\n            static FIELD: Field = Field::new({entry});\n            memory::read(self.0, &FIELD)\n        }}"
        );
        if let Some(write) = write {
            let _ = writeln!(
                out,
                "\n        /// Writes the field: see `memory::write`.\n        pub fn set_{name}(&self, value: {write}) -> Result<(), Error> {{\n            static FIELD: Field = Field::new({entry});\n            memory::write(self.0, &FIELD, value)\n        }}"
            );
        }
    }

    /// The Rust type an argument of a call of `ty` takes.
    fn argument_type(&self, ty: &Ty) -> Option<String> {
        if let Some(number) = self.number(ty) {
            return Some(number.to_owned());
        }
        match self.plain(ty) {
            Ty::Fn(_) => Some("&calls::Thunk".into()),
            Ty::Ptr(Some(inner)) if matches!(self.plain(inner), Ty::Char8) => Some("&[u8]".into()),
            _ => self.write_type(ty),
        }
    }

    /// The Rust type a call of a function that returns `ty` gives.
    fn return_type(&self, ty: &Ty) -> Option<String> {
        if let Some(number) = self.number(ty) {
            return Some(number.to_owned());
        }
        match self.plain(ty) {
            Ty::Ptr(Some(inner)) => match self.plain(inner) {
                Ty::Named(name, args) if args.is_empty() && self.structure_of(name).is_some() => {
                    Some(format!("Option<{}>", Self::path(name)))
                }
                _ => Some("Option<Pointer>".into()),
            },
            Ty::Ptr(None) | Ty::Fn(_) => Some("Option<Pointer>".into()),
            _ => None,
        }
    }

    fn function(
        &self,
        out: &mut String,
        sdk: &str,
        name: &str,
        ty: &angelica_anatomia::FnType,
        text: Option<&str>,
    ) {
        let mut params = Vec::new();
        let mut values = Vec::new();
        for (index, param) in ty.params.iter().enumerate() {
            let Some(rust) = self.argument_type(&param.ty) else {
                return;
            };
            let argument = ident(&param.name.clone().unwrap_or_else(|| format!("arg{index}")));
            params.push(format!("{argument}: {rust}"));
            values.push(format!("{sdk}::memory::IntoValue::into_value({argument})"));
        }
        let (returns, body) = match &ty.ret {
            None => (
                "()".to_owned(),
                "        calls::call(FUNCTION, &args)?;
        Ok(())"
                    .to_owned(),
            ),
            Some(ret) => {
                let Some(rust) = self.return_type(ret) else {
                    return;
                };
                (
                    rust,
                    "        FromValue::from_value(calls::call(FUNCTION, &args)?)".to_owned(),
                )
            }
        };
        let function = ident(&subject(name).replace('.', "_"));
        let _ = writeln!(out);
        doc(out, "    ", text);
        let _ = writeln!(
            out,
            "    pub fn {function}({}) -> Result<{returns}, Error> {{
        const FUNCTION: &str = {};
        let args = [{}];
{body}
    }}",
            params.join(", "),
            literal(name),
            values.join(", ")
        );
    }

    fn global(&self, out: &mut String, name: &str, ty: &Ty, text: Option<&str>) {
        let Some(read) = self.read_type(ty) else {
            return;
        };
        let function = ident(&subject(name).replace('.', "_"));
        let _ = writeln!(out);
        doc(out, "    ", text);
        let _ = writeln!(
            out,
            "    pub fn {function}() -> Result<{read}, Error> {{\n        memory::global({})\n    }}",
            literal(name)
        );
    }
}
